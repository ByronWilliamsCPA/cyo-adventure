@pytest.mark.parametrize("scenario", _load_scenarios(), ids=lambda s: s["id"])
def test_render_reads_nothing_beyond_the_three_model_facing_fields(
    scenario: dict[str, Any], tmp_path: Path
):
    """A record stripped to the three fields renders identically to the real one.

    Narrowing check. If a future edit makes the composer read a fourth
    field, the stripped record raises `KeyError` here. If the composer
    starts reading something it happens to find on the real record, the two
    renders diverge. Either way this goes red without anyone having to
    anticipate which field.
    """
    stripped = {"id": scenario["id"]} | {
        field: scenario[field] for field in _MODEL_FACING_FIELD_NAMES
    }
    stripped_path = _write_scenarios(tmp_path, [stripped])

    from_stripped = render_module.render_paste_block(
        scenario["id"], _TEST_URL, scenarios_path=stripped_path
    )
    from_real = render_module.render_paste_block(scenario["id"], _TEST_URL)
    assert from_stripped == from_real


@pytest.mark.parametrize("scenario", _load_scenarios(), ids=lambda s: s["id"])
def test_no_sentinel_from_outside_the_three_fields_reaches_the_render(
    scenario: dict[str, Any], tmp_path: Path
):
    """Every string leaf outside the three model-facing fields must stay out.

    Sentinel check. The markers are generated by walking the record, so a
    sub-key added under `operator_notes` later, or a brand-new top-level
    field, is covered with no edit here. Substituting markers rather than
    searching for the operator's real prose also removes the
    false-positive risk that operator text shares short substrings with
    the task text.
    """
    marked, sentinels = _sentinelize(scenario)
    assert sentinels, f"{scenario['id']}: no string leaves outside the three fields"
    marked_path = _write_scenarios(tmp_path, [marked])

    rendered = render_module.render_paste_block(
        marked["id"], _TEST_URL, scenarios_path=marked_path
    )
    leaked = [marker for marker in sentinels if marker in rendered]
    assert not leaked, f"{scenario['id']}: operator content reached the block: {leaked}"


def test_sentinel_check_would_catch_an_actual_leak(tmp_path: Path):
    """Proves the sentinel check above is not vacuous.

    Renders a sentinel-marked K0, then appends its marked `operator_notes`
    to the output the way a leaking composer would, and confirms the same
    detector fires. Without this, a sentinel check that never sees a
    positive is indistinguishable from one whose markers never appear
    anywhere.
    """
    k0 = next(s for s in _load_scenarios() if s["id"] == "K0")
    marked, sentinels = _sentinelize(k0)
    marked_path = _write_scenarios(tmp_path, [marked])

    rendered = render_module.render_paste_block(
        marked["id"], _TEST_URL, scenarios_path=marked_path
    )
    leaky = rendered + "\n\n" + json.dumps(marked["operator_notes"])

    assert not [marker for marker in sentinels if marker in rendered]
    assert [marker for marker in sentinels if marker in leaky], (
        "the detector found nothing in a deliberately leaky block, so it would "
        "not have caught a real leak either"
    )


