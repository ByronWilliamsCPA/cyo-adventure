def test_skill_md_step_4_invokes_the_renderer():
    """Step 4 must contain the literal renderer invocation, in a fenced block.

    A safe `render.py` buys nothing if SKILL.md stops calling it. An agent
    invoking this skill reads step 4 and does what it says, so rewriting
    step 4 to compose the block from the scenario record reinstates the
    leak with `render.py` untouched. This is a doc-text assertion, weak in
    general, but here the doc is the program.
    """
    step_4 = _skill_md_step(4)
    assert RENDERER_INVOCATION in step_4, (
        f"SKILL.md step 4 no longer runs the renderer; expected the literal "
        f"{RENDERER_INVOCATION!r} in:\n{step_4}"
    )
    fenced = re.findall(r"```[a-z]*\n(.*?)```", step_4, flags=re.DOTALL)
    assert any(RENDERER_INVOCATION in block for block in fenced), (
        "the renderer invocation must stay inside a fenced code block so it is "
        "copy-pasteable, not buried in prose"
    )


def test_skill_md_names_a_renderer_path_that_resolves_on_disk():
    """The path step 4 names must exist, and be the module the tests exercise.

    This is the half that fires on a renamed or moved renderer rather than
    on a prose bypass: SKILL.md can go stale silently otherwise, and a
    stale instruction is a broken instruction.
    """
    step_4 = _skill_md_step(4)
    match = re.search(r"python3\s+(\S+render\.py)", step_4)
    assert match is not None, f"no renderer path found in SKILL.md step 4:\n{step_4}"

    named = REPO_ROOT / match.group(1)
    assert named.is_file(), f"SKILL.md step 4 names {named}, which does not exist"
    assert named.resolve() == RENDER_MODULE_PATH.resolve(), (
        f"SKILL.md step 4 names {named}, but the module under test is "
        f"{RENDER_MODULE_PATH}"
    )


def test_skill_md_has_no_unnegated_self_composition_instruction():
    """No sentence may tell the agent to build the block itself.

    Backstop to the two checks above, for a mutation that leaves the
    fenced invocation in place and adds a competing instruction beside it.
    Heuristic by nature: it requires every sentence mentioning "yourself"
    to also carry a negation, which is the shape the existing "never by
    composing it yourself" instruction already has.
    """
    offenders = [
        sentence
        for sentence in _sentences(_skill_md_text())
        if _SELF_COMPOSE_RE.search(sentence) and not _NEGATION_RE.search(sentence)
    ]
    assert not offenders, (
        f"SKILL.md appears to instruct composing the paste block by hand: {offenders}"
    )


def test_skill_md_never_instructs_putting_operator_content_in_the_block():
    """No sentence may pair an operator-only field with an insertion verb.

    The existing "Do not append, inline, or otherwise relay any
    `operator_notes` content into the pasted block" sentence passes because
    it is negated. A sentence saying to include
    `operator_notes.expected_observations` does not.
    """
    offenders = [
        sentence
        for sentence in _sentences(_skill_md_text())
        if _OPERATOR_FIELD_RE.search(sentence)
        and _INSERTION_VERB_RE.search(sentence)
        and not _NEGATION_RE.search(sentence)
    ]
    assert not offenders, (
        f"SKILL.md appears to instruct relaying operator-only content: {offenders}"
    )
