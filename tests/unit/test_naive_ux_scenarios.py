def test_every_url_placeholder_in_both_substituted_fields_is_replaced(tmp_path: Path):
    """Repeated and cross-field `<URL>` placeholders must all be substituted.

    The 17 real scenarios each carry exactly one `<URL>`, in `task_text`,
    so they cannot distinguish "replaces every occurrence in both fields"
    from "replaces the first occurrence in `task_text`". This synthetic
    record can.
    """
    synthetic = {
        "id": "SYNTH",
        "persona_text": "persona head <URL> persona tail <URL>",
        "task_text": "task head <URL> task tail <URL>",
        "report_back_questions": ["first question.", "second question."],
    }
    synthetic_path = _write_scenarios(tmp_path, [synthetic])

    rendered = render_module.render_paste_block(
        "SYNTH", _TEST_URL, scenarios_path=synthetic_path
    )
    assert "<URL>" not in rendered
    assert rendered.count(_TEST_URL) == 4, (
        f"expected 4 substitutions, got {rendered.count(_TEST_URL)}: {rendered!r}"
    )


