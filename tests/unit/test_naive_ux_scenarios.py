# The leak property: nothing outside the three model-facing fields is read,
# and nothing outside them is emitted.
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("scenario", _load_scenarios(), ids=lambda s: s["id"])
def test_render_reads_nothing_beyond_the_three_model_facing_fields(
    scenario: dict[str, Any], tmp_path: Path
):
    """A record stripped to the three fields renders identically to the real one.

    Narrowing check. If a future edit makes the composer read a fourth
    field, the stripped record raises `KeyError` here. If the composer
    starts reading something it happens to find on the real record, the two
    renders diverge. Either way this goes red without anyone having to
    anticipate which field.
    """
    stripped = {"id": scenario["id"]} | {
        field: scenario[field] for field in _MODEL_FACING_FIELD_NAMES
    }
    stripped_path = _write_scenarios(tmp_path, [stripped])

