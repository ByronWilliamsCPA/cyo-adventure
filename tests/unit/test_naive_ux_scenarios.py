def _sentinelize(scenario: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Copy `scenario`, replacing every string leaf outside the three fields.

    Walks dicts and lists recursively instead of naming today's
    `operator_notes` sub-keys, so a field added anywhere in the schema
    later is sentinel-marked automatically. `id` is marked too, and the
    marked id is what the caller renders by, which is why nine scenarios
    with entirely empty `operator_notes` still exercise this check.
    """
    counter = itertools.count(1)
    sentinels: list[str] = []

    def walk(node: Any) -> Any:
        if isinstance(node, str):
            marker = f"__LEAK_{next(counter)}__"
            sentinels.append(marker)
            return marker
        if isinstance(node, dict):
            return {key: walk(value) for key, value in node.items()}
        if isinstance(node, list):
            return [walk(item) for item in node]
        return node

    marked = {
        key: value if key in _MODEL_FACING_FIELD_NAMES else walk(value)
        for key, value in scenario.items()
    }
    return marked, sentinels


def _write_scenarios(tmp_path: Path, records: list[dict[str, Any]]) -> Path:
    path = tmp_path / "scenarios.json"
    path.write_text(json.dumps(records), encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# SKILL.md text helpers. SKILL.md is the program an agent runs, so its step 4
# is checked the way a program is checked.
# ---------------------------------------------------------------------------

_NEGATION_RE = re.compile(r"\b(never|not|avoid|without)\b", re.IGNORECASE)
_SELF_COMPOSE_RE = re.compile(r"\byourself\b", re.IGNORECASE)
_OPERATOR_FIELD_RE = re.compile(
    r"operator_notes|operator_setup|operator_note|persona_context"
    r"|expected_observations",
    re.IGNORECASE,
)
# Verbs that would put operator content INTO the block. Deliberately excludes
# "relay" and "paste", which step 4 legitimately uses for telling the operator
# things out of band, outside the pasted text.
_INSERTION_VERB_RE = re.compile(
    r"\b(append\w*|inline\w*|includ\w*|embed\w*|insert\w*|copy|copies|copying)\b",
    re.IGNORECASE,
)


def _skill_md_text() -> str:
    return SKILL_MD_PATH.read_text(encoding="utf-8")


def _skill_md_step(number: int) -> str:
    """Return the text of one top-level numbered step of SKILL.md.

    Steps start at column 0 as `N. `; their continuation lines are
    indented. Returns everything from that marker up to the next
    column-0 numbered step or the next `## ` heading.
    """
    lines = _skill_md_text().splitlines()
    start = next(
        (i for i, line in enumerate(lines) if line.startswith(f"{number}. ")), None
    )
    assert start is not None, f"SKILL.md has no step {number}"
    end = len(lines)
    for i in range(start + 1, len(lines)):
        if re.match(r"^\d+\. ", lines[i]) or lines[i].startswith("## "):
            end = i
            break
    return "\n".join(lines[start:end])


def _sentences(text: str) -> list[str]:
    """Unwrap markdown line wrapping and split into rough sentences.

    Splits on `.`, `:`, `;`, `!` and `?` followed by whitespace. Rough is
    fine: the checks below only ask whether a negation sits in the same
    sentence as a risky instruction, and over-splitting makes them
    stricter, never laxer.
    """
    flat = re.sub(r"\s+", " ", text)
    return [part for part in re.split(r"(?<=[.:;!?])\s+", flat) if part.strip()]


