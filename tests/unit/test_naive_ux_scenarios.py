"""Tests for the naive-ux-check scenario data file and its paste-block renderer.

`scenarios.json` (`.claude/skills/naive-ux-check/scenarios.json`) is the
single source of truth for the 17 naive-user comprehension scenarios
(K0-K4, G0-G7, A0-A3; task D2a). `render.py`
(`.claude/skills/naive-ux-check/render.py`) is the single composer of the
block a human pastes into the Claude-for-Chrome extension: SKILL.md step 4
runs it rather than composing the block itself, so this module imports and
exercises the actual module the skill executes, not a test-local stand-in.

Three properties matter enough to be enforced by structure rather than by a
human reading SKILL.md's instructions:

1. Every scenario round-trips: all required fields are present and
   non-empty, and the id set is exactly the expected 17 with no
   duplicates.
2. Operator-only content (`operator_notes`: operator setup lines, operator
   notes, persona context, and expected-observations paragraphs) can never
   reach the block that gets pasted into the model. SKILL.md says twice,
   emphatically, that a prompt leaking its own expected observations tests
   transcription, not comprehension, so every verdict downstream of a leak
   would be worthless.
3. SKILL.md step 4 keeps running `render.py`, and its stdout is what the
   checks below actually observe. SKILL.md is the program an agent
   executes when it invokes this skill, so an edit that drops the renderer
   invocation and tells the agent to compose the block by hand is a live
   path to the leak, no matter how safe `render.py` itself is. The same
   goes for `main()`: `render_paste_block` is a function nobody pastes,
   and stdout is the artifact, so the CLI is exercised directly rather
   than trusted to be a thin wrapper.

Property 2 is pinned by two generic checks that never rebuild the block:

* a **narrowing** check, that a record stripped to `id` plus the three
  model-facing fields renders byte-identically to the real record, so
  nothing outside those three is *read*; and
* a **sentinel** check, that replacing every string leaf outside those
  three fields with a unique `__LEAK_n__` marker leaves no marker in the
  output, so nothing outside those three is *emitted*. The markers are
  generated by tree-walk rather than by naming fields, so the check
  survives schema growth: a sub-key added under `operator_notes`, or a
  brand-new top-level field, gets a marker without anyone editing this
  file.

The block's *shape* is pinned separately, by hand-transcribed golden blocks
for K0, G4 and A1. An earlier revision compared the render against a
reference function that rebuilt the same f-string from the same three
fields; that reference was a line-for-line clone of the composer, so the
two moved together and the suite pinned nothing about the format. A golden
has to be re-transcribed by a human when the format changes, which is
exactly the friction that was missing.

One claim an earlier revision of this docstring got wrong, corrected here:
a brand-new top-level field in `scenarios.json` is **not** caught merely by
existing. Adding one with the renderer untouched changes no output and
fails nothing, which is correct: an unread field is not a leak. What is
caught is a *leak through* such a field, that is, a field the composer has
also been changed to read. The sentinel check catches that generically, and
the narrowing check makes the composer raise `KeyError` the moment it reads
anything the stripped record does not carry.

The SKILL.md checks come in two strengths, and the difference matters when
reading a green suite:

* **Structural**, and therefore complete for what they claim: step 4 must
  contain the literal renderer invocation inside a fenced block; every
  `python3 <path>` invocation anywhere in SKILL.md must resolve to a file
  on disk; and step 4 may name an operator-only field only in the exact
  sentences grandfathered in `_STEP_4_OPERATOR_FIELD_SENTENCES`, fenced
  templates included. A new occurrence anywhere in step 4 fails, and the
  grandfather list is a ratchet that can only shrink.
* **Tripwires**, and therefore incomplete by construction: the two
  prose checks that look for an instruction to hand-compose the block or
  to relay operator content into it. They match a finite list of English
  verbs against rough sentence splits. They catch the ordinary phrasings
  a maintainer or an agent would actually reach for, which is worth
  having, but no verb list is closed and no negation heuristic is
  airtight. Read a pass from them as "no common phrasing of the
  instruction is present", never as "the leak cannot be reinstated in
  prose". Prose is not a language a test can fully police; the structural
  checks above are what actually hold the line.

What none of this defends against, stated plainly rather than left to be
discovered: operator-style text written straight into `persona_text`,
`task_text`, or `report_back_questions` reaches the model, because those
three fields are model-facing by design. The operator/model split is a
boundary between fields, not a classifier of content, so keeping "what the
operator should notice" out of those three is an authoring convention, not
a control any test here can enforce.
"""

